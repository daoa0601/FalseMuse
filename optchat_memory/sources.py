"""Read the recorded formats, keeping scope-A messages separate from transcripts."""

from dataclasses import dataclass
from datetime import datetime, timezone
import json
import re
from pathlib import Path
from typing import Iterator, Literal

Kind = Literal["user", "talk", "work"]
ROOTS = {
    "codex": ".codex/sessions",
    "codex-archived": ".codex/archived_sessions",
    "claude": ".claude/projects",
    "prime": ".prime/agent/sessions",
    "pi": ".pi/agent/sessions",
}
HARNESS = (
    "<codex_internal_context", "<recommended_plugins>", "# AGENTS.md instructions",
    "<environment_context>", "<skill>", "<goal_context>", "<turn_aborted>",
    "<heartbeat>", "<scheduled-task", "<local-command-",
    "<command-name>", "<command-message>",
    "Caveat: The messages below were generated by the user while running local commands.",
    "This session is being continued", "[Request interrupted",
    "<external_codex_apps_open_page>", "<system-reminder>",
)
REPORTS = ("<subagent_notification>", "<task-notification>", "<codex_delegation>")
CONTINUATION_CHECK = "Analyze this conversation and determine: Does the assistant have more autonomous work to do RIGHT NOW?"
LOGICAL_SUBAGENT = "You are logical subagent "
HARNESS_SUPERVISOR = "You are the supervisor inside a deterministic agent harness."
PATCH_SELECTOR = re.compile(r"You are evaluating \d+ candidate patches for SWE-bench instance ")
ISSUE_CONTINUATION = re.compile(r"Continue working on [A-Z]+-\d+: .*\nThis is turn \d+\. Check the workspace state and continue from where the previous turn left off\.")
EDITOR_CONTEXT = ("# Files mentioned by the user", "# Applications mentioned by the user", "# In app browser:", "# Context from my IDE setup:")


@dataclass(frozen=True)
class Session:
    source: str
    path: Path
    id: str
    started_at: str
    kind: Literal["main", "subagent", "harness"]
    snapshot_bytes: int

    @property
    def name(self) -> str:
        return f"{self.source}/{self.id}"


@dataclass(frozen=True)
class Message:
    kind: Kind
    text: str
    timestamp: str
    line: int


def discover(home: Path, sources: list[str]) -> tuple[list[Session], int, int]:
    sessions: dict[tuple[str, str], Session] = {}
    duplicates = 0
    non_chat_files = 0
    for source in sources:
        root = home / ROOTS[source]
        paths = list(root.rglob("*.jsonl"))
        if source == "prime":
            paths.extend((home / ".prime/agent/session-artifacts").glob("*/sub-*/*.jsonl"))
        for path in sorted(paths):
            if path.name in ("semantic-edges.jsonl", "journal.jsonl"):
                non_chat_files += 1
                continue
            session = identify(source, root, path)
            family = "codex" if source == "codex-archived" else source
            key = (family, session.id)
            previous = sessions.get(key)
            if previous:
                duplicates += 1
                if previous.snapshot_bytes >= session.snapshot_bytes:
                    continue
            sessions[key] = session
    return sorted(sessions.values(), key=lambda s: (s.started_at, s.name)), duplicates, non_chat_files


def identify(source: str, root: Path, path: Path) -> Session:
    size = path.stat().st_size
    identifier = path.stem
    start = None
    subagent = "subagents" in path.parts or path.name.startswith("agent-")
    first_user = ""
    metadata = None
    if source == "prime":
        subagent = subagent or any(part.startswith("sub-") for part in path.parts)
    if source == "pi":
        subagent = subagent or any(part.startswith("run-") for part in path.relative_to(root).parts)
    for line, event in records(path, size):
        timestamp = event.get("timestamp") or event.get("snapshot", {}).get("timestamp")
        if timestamp and start is None:
            start = utc_timestamp(timestamp)
        if event.get("type") == "session_meta":
            # A forked rollout copies its parent's session_meta after its own; the first is the file's.
            if metadata is not None:
                continue
            metadata = event["payload"]
            identifier = metadata["id"]
            start = utc_timestamp(metadata.get("timestamp", timestamp))
            origin = metadata.get("source")
            subagent = subagent or origin == "subagent" or (
                isinstance(origin, dict) and "subagent" in origin
            )
            continue
        if event.get("type") == "session":
            identifier = event["id"]
            start = utc_timestamp(timestamp)
            subagent = subagent or event.get("rlmDepth", 0) > 0
            continue
        if source == "claude":
            subagent = subagent or event.get("isSidechain", False)
            # Resumed files can begin with a record carrying the preceding sessionId.
            # The filename identifies the recording; workers also share their parent's id.
            identifier = path.stem
        payload = event.get("payload", {}) if source.startswith("codex") else event.get("message", {})
        if payload.get("role") == "user":
            text = user_text(text_blocks(payload.get("content")))
            if session_kind(subagent, text) != "main" or classify("user", text):
                first_user = text
                break
        if line >= 100:
            break
    if start is None:
        raise ValueError(f"{path}: no session timestamp in the first 100 records")
    if not identifier or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_." for c in identifier):
        raise ValueError(f"{path}: session id cannot be used as a filename")
    kind = session_kind(subagent, first_user)
    return Session(source, path, identifier, start, kind, size)


def records(path: Path, snapshot_bytes: int | None = None) -> Iterator[tuple[int, dict]]:
    """Read a fixed file boundary; a live writer's unfinished last record is deferred."""
    limit = path.stat().st_size if snapshot_bytes is None else snapshot_bytes
    with path.open("rb") as handle:
        line = 0
        while handle.tell() < limit:
            raw = handle.readline(limit - handle.tell())
            line += 1
            if not raw:
                raise ValueError(f"{path}:{line}: recording ended before its snapshot boundary")
            if not raw.strip():
                continue
            try:
                event = json.loads(raw)
            except (ValueError, UnicodeDecodeError) as error:
                if handle.tell() == limit and not raw.endswith(b"\n"):
                    return
                raise ValueError(f"{path}:{line}: invalid JSON record") from error
            if not isinstance(event, dict):
                raise ValueError(f"{path}:{line}: expected a JSON object")
            yield line, event


def scope_a(session: Session, transcript: Path) -> list[Message]:
    if session.source.startswith("codex"):
        return codex_messages(session, transcript)
    messages: dict[str, tuple[int, Message]] = {}
    claude_replies: dict[str, dict] = {}
    for order, wrapper in records(transcript):
        event = wrapper.get("event", {})
        line = wrapper["line"]
        timestamp = event.get("timestamp") or session.started_at
        if session.source == "claude":
            payload = event.get("message", {})
            if event.get("type") == "assistant":
                reply_id = payload.get("id", f"line-{line}")
                reply = claude_replies.setdefault(reply_id, {"order": order, "blocks": {}})
                reply["blocks"][event.get("uuid", f"line-{line}")] = (line, timestamp, payload)
                continue
            if event.get("type") != "user" or event.get("isMeta"):
                continue
        else:
            if event.get("type") == "custom_message":
                report = custom_report(event)
                if report:
                    messages[f"report-{line}"] = (order, Message("work", report, timestamp, line))
                continue
            if event.get("type") != "message":
                continue
            payload = event.get("message", {})
            if payload.get("role") == "assistant" and payload.get("stopReason") not in (None, "stop"):
                continue
        role = payload.get("role")
        if role not in ("user", "assistant"):
            continue
        content = payload.get("content")
        if role == "assistant" and has_tools(content):
            continue
        text = text_blocks(content)
        if role == "user":
            text = user_text(text)
        kind = classify(role, text)
        if kind:
            key = event.get("uuid") or payload.get("id") or event.get("id") or f"line-{line}"
            messages[key] = (order, Message(kind, text, timestamp, line))
    for reply_id, reply in claude_replies.items():
        blocks = list(reply["blocks"].values())
        if any(has_tools(payload.get("content")) for _, _, payload in blocks):
            continue
        text = "\n".join(text_blocks(payload.get("content")) for _, _, payload in blocks).strip()
        if classify("assistant", text):
            line, timestamp, _ = blocks[0]
            messages[f"assistant-{reply_id}"] = (reply["order"], Message("talk", text, timestamp, line))
    return [message for _, message in sorted(messages.values(), key=lambda pair: pair[0])]


def codex_messages(session: Session, transcript: Path) -> list[Message]:
    messages = []
    pending_final = None
    for order, wrapper in records(transcript):
        event = wrapper.get("event", {})
        payload = event.get("payload", {})
        line = wrapper["line"]
        timestamp = event.get("timestamp") or session.started_at
        if event.get("type") == "event_msg":
            if payload.get("type") == "task_complete":
                text = payload.get("last_agent_message")
                if pending_final:
                    messages.append(pending_final)
                elif isinstance(text, str) and classify("assistant", text):
                    messages.append((order, Message("talk", text, timestamp, line)))
                pending_final = None
            elif payload.get("type") == "task_started" and pending_final:
                messages.append(pending_final)
                pending_final = None
            continue
        if event.get("type") != "response_item" or payload.get("type") != "message":
            continue
        role = payload.get("role")
        text = text_blocks(payload.get("content"))
        if role == "user":
            text = user_text(text)
            kind = classify(role, text)
            if kind:
                messages.append((order, Message(kind, text, timestamp, line)))
        elif role == "assistant" and classify(role, text) and payload.get("recipient") in (None, "all"):
            if payload.get("phase") == "final_answer" or payload.get("channel") == "final":
                pending_final = (order, Message("talk", text, timestamp, line))
    if pending_final:
        messages.append(pending_final)
    return [message for _, message in sorted(messages, key=lambda pair: pair[0])]


def custom_report(event: dict) -> str | None:
    if event.get("customType") == "subagent-notify":
        return text_blocks(event.get("content"))
    if event.get("customType") == "agent_message":
        details = event.get("details", {})
        if details.get("fromRelationship") == "child":
            origin = details.get("from", {})
            identifier = origin.get("sessionId", origin.get("sessionName", "worker"))
            return f"[{identifier}] {details.get('message', event.get('content', ''))}"
    return None


def classify(role: str, text: str) -> Kind | None:
    if not text.strip():
        return None
    if text.lstrip().startswith("<heartbeat>") and "<decision>DONT_NOTIFY</decision>" in text:
        return None
    if role == "assistant":
        return "talk"
    stripped = text.lstrip()
    if stripped.startswith(REPORTS):
        return "work"
    if stripped.startswith("<user_action>") and "<action>review</action>" in stripped:
        return "work"
    if stripped.startswith(HARNESS):
        return None
    return "user"


def session_kind(subagent: bool, first_user: str) -> Literal["main", "subagent", "harness"]:
    prompt = first_user.lstrip()
    if subagent or prompt.startswith((LOGICAL_SUBAGENT, "<codex_delegation>", "You are a coding agent working on issue **")) or ISSUE_CONTINUATION.match(prompt):
        return "subagent"
    if prompt.startswith((CONTINUATION_CHECK, HARNESS_SUPERVISOR, "<scheduled-task")) or PATCH_SELECTOR.match(prompt):
        return "harness"
    return "main"


def user_text(text: str) -> str:
    """Keep the human request attached to editor context or a leading reminder."""
    stripped = text.lstrip()
    if stripped.startswith(EDITOR_CONTEXT):
        _, separator, request = stripped.partition("## My request for Codex:")
        return request.lstrip() if separator else ""
    if stripped.startswith("<user_shell_command>"):
        _, separator, command = stripped.partition("<command>")
        return command.partition("</command>")[0].strip() if separator else ""
    if stripped.startswith("<system-reminder>"):
        _, separator, request = stripped.partition("</system-reminder>")
        if separator:
            return user_text(request.lstrip())
    return text


def text_blocks(content: object) -> str:
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    return "\n".join(
        block.get("text", "") for block in content
        if isinstance(block, dict) and block.get("type") in ("text", "input_text", "output_text")
    )


def has_tools(content: object) -> bool:
    return isinstance(content, list) and any(
        isinstance(block, dict) and block.get("type") in ("tool_use", "toolCall")
        for block in content
    )


def utc_timestamp(value: str | int | float) -> str:
    date = datetime.fromtimestamp(value / 1000, timezone.utc) if isinstance(value, (int, float)) else datetime.fromisoformat(value.replace("Z", "+00:00"))
    if date.tzinfo is None:
        raise ValueError("session timestamp has no timezone")
    return date.astimezone(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
